"""The bundled run, and the promise that it needs no ORCA.

The demo exists so that someone can see what dftfig produces before deciding whether to
install a quantum chemistry program. That promise is only worth making if it is tested,
so the test that matters here is the one that runs the pipeline with ORCA removed from
the environment entirely.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pandas as pd
import pytest

from dftfig import config as C
from dftfig import demo


def test_the_bundled_run_is_present_and_complete():
    """Four ORCA outputs and four cubes per molecule, or the demo cannot build a figure."""
    runs = demo.DATA / "runs"
    molecules = sorted(p.name for p in runs.iterdir() if p.is_dir())
    assert molecules == ["ANIL", "PHEN"]

    for name in molecules:
        d = runs / name / "water"
        for stage in ("opt", "sp", "cat", "ani"):
            out = d / f"{name}_water_{stage}.out"
            assert out.exists(), out
            assert "ORCA TERMINATED NORMALLY" in out.read_text(errors="ignore")
        for cube in ("eldens", "esp", "homo", "lumo"):
            assert (d / f"{cube}.cube.gz").exists()
    assert (demo.DATA / "ANIL.sdf").exists()
    assert (demo.DATA / "PHEN.sdf").exists()


def test_unpack_decompresses_the_cubes_and_writes_a_loadable_config(tmp_path):
    dest = demo.unpack(tmp_path / "d")

    cube = dest / "runs" / "ANIL" / "water" / "eldens.cube"
    assert cube.exists() and not cube.with_suffix(".cube.gz").exists()
    assert cube.read_text(errors="ignore").lstrip().startswith("Cube data generated by ORCA")

    cfg = C.load(dest / "config.yaml")          # raises if the config does not validate
    assert sorted(Path(cfg["molecules"]["sdf_dir"]).glob("*.sdf")) != []
    assert Path(cfg["execution"]["work_dir"]) == dest / "runs"


def test_unpack_is_repeatable(tmp_path):
    """Re-running the demo into an existing directory must not fail or corrupt it."""
    demo.unpack(tmp_path / "d")
    dest = demo.unpack(tmp_path / "d")
    assert (dest / "runs" / "PHEN" / "water" / "homo.cube").exists()


def test_the_configured_level_of_theory_matches_the_bundled_outputs(tmp_path):
    """The figures stamp their method footnote from the config, so a mismatch here would
    print a level of theory that does not describe the data underneath it."""
    dest = demo.unpack(tmp_path / "d")
    cfg = C.load(dest / "config.yaml")
    keywords = (dest / "runs" / "ANIL" / "water" / "ANIL_water_opt.out").read_text(
        errors="ignore")

    assert cfg["theory"]["functional"].upper() in keywords.upper()
    assert cfg["theory"]["basis_opt"].upper() in keywords.upper()
    assert cfg["solvation"]["model"].upper() in keywords.upper()


def test_demo_runs_with_no_orca_on_the_path(tmp_path, child_env):
    """The headline claim, tested the only way it can honestly be tested: in a fresh
    interpreter with ORCA stripped from the environment."""
    script = (
        f"import sys; sys.argv = ['dft', 'demo', {str(tmp_path / 'run')!r}]\n"
        "from dftfig import cli\n"
        "raise SystemExit(cli.main())\n"
    )
    pruned = os.pathsep.join(
        p for p in os.environ.get("PATH", "").split(os.pathsep)
        if p and not (Path(p) / "orca").exists())
    env = child_env(ORCA_PATH=None, PATH=pruned)

    done = subprocess.run([sys.executable, "-c", script], env=env,
                          capture_output=True, text=True, timeout=900)
    assert done.returncode == 0, done.stdout[-3000:] + done.stderr[-3000:]

    table = pd.read_csv(tmp_path / "run" / "runs" / "descriptors.csv")
    assert sorted(table["molecule"]) == ["ANIL", "PHEN"]
    atoms = pd.read_csv(tmp_path / "run" / "runs" / "atom_descriptors.csv")
    assert len(atoms) == 27                      # aniline 14 + phenol 13


@pytest.mark.pymol
@pytest.mark.slow
def test_demo_builds_every_figure_when_pymol_is_present(tmp_path):
    assert demo.run(tmp_path / "run") == 0
    figures = {p.stem for p in (tmp_path / "run" / "runs" / "figures").glob("*.png")}
    assert figures == {"frontier_orbitals", "speciation", "lipophilicity",
                       "mpo_metabolism"}
